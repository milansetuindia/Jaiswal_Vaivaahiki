/*==========================================================
                WEBSITE LANGUAGE FUNCTIONS
==========================================================*/


function getCurrentLanguage() {

    return localStorage.getItem(
        LANGUAGE_CONFIG.storageKey
    ) || LANGUAGE_CONFIG.defaultLanguage;

}


function setCurrentLanguage(language) {

    if (
        language !== "en" &&
        language !== "hi"
    ) {
        language = LANGUAGE_CONFIG.defaultLanguage;
    }

    localStorage.setItem(
        LANGUAGE_CONFIG.storageKey,
        language
    );

    document.documentElement.lang = language;

}


function translateText(text) {

    const language = getCurrentLanguage();

    const dictionary =
        TRANSLATIONS[language] || TRANSLATIONS.en;

    return dictionary[text] !== undefined
        ? dictionary[text]
        : text;

}


/*==========================================================
                NORMALIZE TEXT
==========================================================*/

function normalizeTranslationText(text) {

    return text
        .replace(/\s+/g, " ")
        .trim();

}


/*==========================================================
                TRANSLATE TEXT NODES
==========================================================*/

function translateTextNodes(root = document.body) {

    if (!root) {
        return;
    }

    const walker = document.createTreeWalker(
        root,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode(node) {

                const parent = node.parentElement;

                if (!parent) {
                    return NodeFilter.FILTER_REJECT;
                }

                const tag = parent.tagName.toLowerCase();

                if (
                    tag === "script" ||
                    tag === "style" ||
                    tag === "noscript"
                ) {
                    return NodeFilter.FILTER_REJECT;
                }

                if (
                    parent.closest("[data-no-translate]")
                ) {
                    return NodeFilter.FILTER_REJECT;
                }

                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    const nodes = [];

    let node;

    while (
        node = walker.nextNode()
    ) {
        nodes.push(node);
    }

    nodes.forEach(textNode => {

        /*
         * Store the original English text on the
         * text node so that Hindi → English works.
         */
        if (!textNode.__originalLanguageText) {

            const normalized =
                normalizeTranslationText(
                    textNode.nodeValue
                );

            if (!normalized) {
                return;
            }

            textNode.__originalLanguageText =
                normalized;
        }

        const originalText =
            textNode.__originalLanguageText;

        const translated =
            translateText(originalText);

        /*
         * Preserve spaces around the text.
         */
        const currentValue =
            textNode.nodeValue;

        const leadingSpaces =
            currentValue.match(/^\s*/)?.[0] || "";

        const trailingSpaces =
            currentValue.match(/\s*$/)?.[0] || "";

        textNode.nodeValue =
            leadingSpaces +
            translated +
            trailingSpaces;

    });

}



/*==========================================================
                TRANSLATE PLACEHOLDERS
==========================================================*/
function translatePlaceholders() {

    const language =
        getCurrentLanguage();

    const dictionary =
        TRANSLATIONS[language] ||
        TRANSLATIONS.en;

    document
        .querySelectorAll(
            "input[placeholder], textarea[placeholder]"
        )
        .forEach(element => {

            /*
             * Store the original English placeholder
             * only once.
             */
            if (!element.dataset.originalPlaceholder) {

                element.dataset.originalPlaceholder =
                    element.getAttribute("placeholder") || "";
            }

            const original =
                normalizeTranslationText(
                    element.dataset.originalPlaceholder
                );

            if (
                dictionary[original] !== undefined
            ) {

                element.setAttribute(
                    "placeholder",
                    dictionary[original]
                );

            }

        });

}


/*==========================================================
                TRANSLATE SELECT OPTIONS
==========================================================*/

function translateSelectOptions() {

    const language =
        getCurrentLanguage();

    const dictionary =
        TRANSLATIONS[language] ||
        TRANSLATIONS.en;

    document
        .querySelectorAll("select option")
        .forEach(option => {

            /*
             * Store the original English option text
             * only once.
             */
            if (!option.dataset.originalText) {

                option.dataset.originalText =
                    option.textContent;
            }

            const original =
                normalizeTranslationText(
                    option.dataset.originalText
                );

            if (
                dictionary[original] !== undefined
            ) {

                option.textContent =
                    dictionary[original];

            }

        });

}

