/*==========================================================
                TRANSLATE DYNAMIC REVIEW
==========================================================*/

function translateReviewLabels() {

    const language =
        getCurrentLanguage();

    const dictionary =
        TRANSLATIONS[language] ||
        TRANSLATIONS.en;

    document
        .querySelectorAll(".review-item strong")
        .forEach(element => {

            /*
             * Store the original English label once.
             * This allows English ↔ Hindi switching
             * without losing the original key.
             */
            if (!element.dataset.originalText) {

                element.dataset.originalText =
                    normalizeTranslationText(
                        element.textContent
                    );

            }

            const originalText =
                element.dataset.originalText;

            if (
                dictionary[originalText] !== undefined
            ) {

                element.textContent =
                    dictionary[originalText];

            }

        });

}

